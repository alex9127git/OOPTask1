package ru.vsu.cs.nagajcev_a_a.repeat;

/**
 * Порядковый номер дня недели в месяце для {@link CustomMonthRepeat}.
 * <p>
 * Вариантов «пятый» нет: пятый понедельник есть не в каждом месяце, а первый–четвёртый
 * и последний–четвёртый с конца есть всегда.
 */
public enum CustomMonthRepeatPattern {
    /** Первый день недели месяца. */
    FIRST(1),
    /** Второй день недели месяца. */
    SECOND(2),
    /** Третий день недели месяца. */
    THIRD(3),
    /** Четвёртый день недели месяца. */
    FOURTH(4),
    /** Последний день недели месяца. */
    LAST(-1),
    /** Предпоследний день недели месяца. */
    SECOND_TO_LAST(-2),
    /** Третий с конца день недели месяца. */
    THIRD_TO_LAST(-3),
    /** Четвёртый с конца день недели месяца. */
    FOURTH_TO_LAST(-4);

    private final int value;

    CustomMonthRepeatPattern(int value) {
        this.value = value;
    }

    /**
     * Возвращает номер дня недели в месяце.
     *
     * @return положительное число — номер с начала месяца (1 — первый), отрицательное — с конца (-1 — последний)
     */
    public int getValue() {
        return value;
    }
}
